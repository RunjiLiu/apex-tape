#!/usr/bin/env python3
"""Export v_ds_bars_indicators into src/data/bars.ts for the Vite app.

The browser cannot open DuckDB, so the page reads this snapshot.
Regenerate it when the database changes.
"""

from __future__ import annotations

import json
from pathlib import Path

import duckdb

CANDIDATES = [
    Path("/cursor/stores/store-660504dc-3643-423f-8daa-b0df0ebd73a0/trading.duckdb"),
    Path("/workspace/trading.duckdb"),
]
OUT = Path(__file__).resolve().parents[1] / "src" / "data" / "bars.ts"
VIEW = "v_ds_bars_indicators"


def db_path() -> Path:
    for candidate in CANDIDATES:
        if candidate.is_file():
            return candidate
    raise SystemExit("trading.duckdb not found in the store path or /workspace")


def num(value: object, places: int | None = None) -> str:
    if value is None:
        return "null"
    number = float(value)
    if places is not None:
        number = round(number, places)
    return repr(number)


def main() -> None:
    path = db_path()
    con = duckdb.connect(str(path), read_only=True)
    rows = con.execute(
        f"""
        SELECT symbol, trade_date::VARCHAR,
               open, high, low, close, volume,
               rsi_14, macd, macd_signal, macd_hist,
               ret_1d, ret_5d, ret_20d, rs_5d, rs_20d,
               atr_14, atr_pct, atr_pct_rank_20,
               dist_sma20_pct, dist_sma50_pct, dist_ema9_pct, dist_ema21_pct,
               vol_ratio_20, trend_tag, vol_tag, ds_source
        FROM {VIEW}
        ORDER BY symbol, trade_date
        """
    ).fetchall()
    lines = [
        "/* Generated by scripts/export_bars.py. Do not edit by hand. */",
        f"export const DATA_SOURCE = {json.dumps(str(path))};",
        f"export const DATA_VIEW = {json.dumps(VIEW)};",
        "export interface RawBar {",
        "  symbol: string;",
        "  tradeDate: string;",
        "  open: number;",
        "  high: number;",
        "  low: number;",
        "  close: number;",
        "  volume: number;",
        "  rsi14: number | null;",
        "  macd: number | null;",
        "  macdSignal: number | null;",
        "  macdHist: number | null;",
        "  ret1d: number | null;",
        "  ret5d: number | null;",
        "  ret20d: number | null;",
        "  rs5d: number | null;",
        "  rs20d: number | null;",
        "  atr14: number | null;",
        "  atrPct: number | null;",
        "  atrPctRank20: number | null;",
        "  distSma20Pct: number | null;",
        "  distSma50Pct: number | null;",
        "  distEma9Pct: number | null;",
        "  distEma21Pct: number | null;",
        "  volRatio20: number | null;",
        "  trendTag: string | null;",
        "  volTag: string | null;",
        "  dsSource: string | null;",
        "}",
        "export const RAW_BARS: RawBar[] = [",
    ]
    for row in rows:
        (
            symbol, trade_date, open_, high, low, close, volume,
            rsi, macd, signal, hist,
            ret1, ret5, ret20, rs5, rs20,
            atr, atr_pct, atr_rank,
            sma20, sma50, ema9, ema21,
            vol_ratio, trend, vol_tag, source,
        ) = row
        lines.append(
            "  {"
            f" symbol: {json.dumps(symbol)}, tradeDate: {json.dumps(trade_date)},"
            f" open: {num(open_, 4)}, high: {num(high, 4)}, low: {num(low, 4)}, close: {num(close, 4)},"
            f" volume: {int(volume)},"
            f" rsi14: {num(rsi, 4)}, macd: {num(macd, 6)}, macdSignal: {num(signal, 6)}, macdHist: {num(hist, 6)},"
            f" ret1d: {num(ret1, 6)}, ret5d: {num(ret5, 6)}, ret20d: {num(ret20, 6)},"
            f" rs5d: {num(rs5, 6)}, rs20d: {num(rs20, 6)},"
            f" atr14: {num(atr, 4)}, atrPct: {num(atr_pct, 6)}, atrPctRank20: {num(atr_rank, 2)},"
            f" distSma20Pct: {num(sma20, 6)}, distSma50Pct: {num(sma50, 6)},"
            f" distEma9Pct: {num(ema9, 6)}, distEma21Pct: {num(ema21, 6)},"
            f" volRatio20: {num(vol_ratio, 4)},"
            f" trendTag: {json.dumps(trend)}, volTag: {json.dumps(vol_tag)}, dsSource: {json.dumps(source)} }},"
        )
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(rows)} rows to {OUT} from {path}")


if __name__ == "__main__":
    main()
