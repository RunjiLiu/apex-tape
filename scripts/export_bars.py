#!/usr/bin/env python3
"""Export the unified daily tables into src/data/bars.ts.

Bars come from bars_daily. Factors come from ds_indicators_daily, joined on
symbol + trade_date. RSI and MACD come from indicators_daily on the same key
when that row exists. The source column stays in the database and is not
written into the snapshot.
"""

from __future__ import annotations

import json
import shutil
import tempfile
from pathlib import Path

import duckdb

CANDIDATES = [
    Path("/cursor/stores/store-660504dc-3643-423f-8daa-b0df0ebd73a0/trading.duckdb"),
    Path("/workspace/trading.duckdb"),
]
OUT = Path(__file__).resolve().parents[1] / "src" / "data" / "bars.ts"
BARS = "bars_daily"
FACTORS = "ds_indicators_daily"
OSCILLATORS = "indicators_daily"


def db_path() -> Path:
    for candidate in CANDIDATES:
        if candidate.is_file():
            return candidate
    raise SystemExit("trading.duckdb not found in the store path or /workspace")


def connect(path: Path) -> duckdb.DuckDBPyConnection:
    try:
        return duckdb.connect(str(path), read_only=True)
    except duckdb.IOException:
        copy = Path(tempfile.gettempdir()) / "trading-export.duckdb"
        shutil.copy2(path, copy)
        return duckdb.connect(str(copy), read_only=True)


def rnd(value: object, places: int) -> float | None:
    if value is None:
        return None
    return round(float(value), places)


def main() -> None:
    path = db_path()
    con = connect(path)
    rows = con.execute(
        f"""
        SELECT b.symbol, b.trade_date::VARCHAR,
               b.open, b.high, b.low, b.close, b.volume,
               i.rsi_14, i.macd, i.macd_signal, i.macd_hist,
               d.ret_1d, d.ret_5d, d.ret_20d, d.ret_60d,
               d.rs_5d, d.rs_20d,
               d.atr_14, d.atr_pct,
               d.atr_pct_rank_20, d.atr_pct_rank_60, d.atr_pct_rank_252,
               d.dist_sma20_pct, d.dist_sma50_pct, d.dist_sma200_pct,
               d.dist_ema9_pct, d.dist_ema21_pct,
               d.vol_ratio_20, d.trend_tag, d.vol_tag
        FROM {BARS} b
        LEFT JOIN {FACTORS} d
          ON b.symbol = d.symbol AND b.trade_date = d.trade_date
        LEFT JOIN {OSCILLATORS} i
          ON b.symbol = i.symbol AND b.trade_date = i.trade_date
        ORDER BY b.symbol, b.trade_date
        """
    ).fetchall()
    lines = [
        "/* Generated by scripts/export_bars.py. Do not edit by hand. */",
        f"export const DATA_SOURCE = {json.dumps(str(path))};",
        f"export const BARS_TABLE = {json.dumps(BARS)};",
        f"export const FACTOR_TABLE = {json.dumps(FACTORS)};",
        f"export const OSCILLATOR_TABLE = {json.dumps(OSCILLATORS)};",
        "export interface RawBar {",
        "  symbol: string;",
        "  tradeDate: string;",
        "  open: number;",
        "  high: number;",
        "  low: number;",
        "  close: number;",
        "  volume: number;",
        "  rsi14: number | null;",
        "  macd: number | null;",
        "  macdSignal: number | null;",
        "  macdHist: number | null;",
        "  ret1d: number | null;",
        "  ret5d: number | null;",
        "  ret20d: number | null;",
        "  ret60d: number | null;",
        "  rs5d: number | null;",
        "  rs20d: number | null;",
        "  atr14: number | null;",
        "  atrPct: number | null;",
        "  atrPctRank20: number | null;",
        "  atrPctRank60: number | null;",
        "  atrPctRank252: number | null;",
        "  distSma20Pct: number | null;",
        "  distSma50Pct: number | null;",
        "  distSma200Pct: number | null;",
        "  distEma9Pct: number | null;",
        "  distEma21Pct: number | null;",
        "  volRatio20: number | null;",
        "  trendTag: string | null;",
        "  volTag: string | null;",
        "}",
    ]
    payload = []
    for row in rows:
        (
            symbol, trade_date, open_, high, low, close, volume,
            rsi, macd, signal, hist,
            ret1, ret5, ret20, ret60, rs5, rs20,
            atr, atr_pct, rank20, rank60, rank252,
            sma20, sma50, sma200, ema9, ema21,
            vol_ratio, trend, vol_tag,
        ) = row
        payload.append({
            "symbol": symbol,
            "tradeDate": trade_date,
            "open": round(float(open_), 4),
            "high": round(float(high), 4),
            "low": round(float(low), 4),
            "close": round(float(close), 4),
            "volume": int(volume),
            "rsi14": rnd(rsi, 4),
            "macd": rnd(macd, 6),
            "macdSignal": rnd(signal, 6),
            "macdHist": rnd(hist, 6),
            "ret1d": rnd(ret1, 6),
            "ret5d": rnd(ret5, 6),
            "ret20d": rnd(ret20, 6),
            "ret60d": rnd(ret60, 6),
            "rs5d": rnd(rs5, 6),
            "rs20d": rnd(rs20, 6),
            "atr14": rnd(atr, 4),
            "atrPct": rnd(atr_pct, 6),
            "atrPctRank20": rnd(rank20, 2),
            "atrPctRank60": rnd(rank60, 2),
            "atrPctRank252": rnd(rank252, 2),
            "distSma20Pct": rnd(sma20, 6),
            "distSma50Pct": rnd(sma50, 6),
            "distSma200Pct": rnd(sma200, 6),
            "distEma9Pct": rnd(ema9, 6),
            "distEma21Pct": rnd(ema21, 6),
            "volRatio20": rnd(vol_ratio, 4),
            "trendTag": trend,
            "volTag": vol_tag,
        })
    lines.append(f"export const RAW_BARS = JSON.parse({json.dumps(json.dumps(payload, separators=(',', ':')))}) as RawBar[];")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(rows)} rows to {OUT} from {path}")


if __name__ == "__main__":
    main()
