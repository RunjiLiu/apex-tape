#!/usr/bin/env python3
"""Export Baidu QQQ daily bars joined to DS factors.

OHLC and volume come from v_bars_baidu_daily. Factors come from
ds_baidu_qqq_daily. The join is symbol + trade_date + ts_et, and only
adjust_type = split_only is kept. This snapshot is separate from the
Twelve Data file src/data/bars.ts.
"""

from __future__ import annotations

import json
from pathlib import Path

import duckdb

CANDIDATES = [
    Path("/cursor/stores/store-660504dc-3643-423f-8daa-b0df0ebd73a0/trading.duckdb"),
    Path("/workspace/trading.duckdb"),
]
OUT = Path(__file__).resolve().parents[1] / "src" / "data" / "bars_baidu_qqq.ts"
BARS_VIEW = "v_bars_baidu_daily"
FACTOR_TABLE = "ds_baidu_qqq_daily"
ADJUST = "split_only"


def db_path() -> Path:
    for candidate in CANDIDATES:
        if candidate.is_file():
            return candidate
    raise SystemExit("trading.duckdb not found in the store path or /workspace")


def num(value: object, places: int | None = None) -> str:
    if value is None:
        return "null"
    number = float(value)
    if places is not None:
        number = round(number, places)
    return repr(number)


def main() -> None:
    path = db_path()
    con = duckdb.connect(str(path), read_only=True)
    rows = con.execute(
        f"""
        SELECT b.symbol, b.trade_date::VARCHAR,
               b.open, b.high, b.low, b.close, b.volume,
               b.adjust_type,
               d.ret_1d, d.ret_5d, d.ret_20d, d.ret_60d,
               d.atr_14, d.atr_pct, d.atr_pct_rank_60, d.atr_pct_rank_252,
               d.dist_sma20_pct, d.dist_sma50_pct, d.dist_sma200_pct,
               d.dist_ema9_pct, d.dist_ema21_pct,
               d.vol_ratio_20, d.trend_tag, d.vol_tag, d.source
        FROM {BARS_VIEW} b
        LEFT JOIN {FACTOR_TABLE} d
          ON b.symbol = d.symbol
         AND b.trade_date = d.trade_date
         AND b.ts_et = d.ts_et
        WHERE b.symbol = 'QQQ' AND b.adjust_type = '{ADJUST}'
        ORDER BY b.trade_date
        """
    ).fetchall()
    lines = [
        "/* Generated by scripts/export_bars_baidu.py. Do not edit by hand. */",
        f"export const BAIDU_DB = {json.dumps(str(path))};",
        f"export const BAIDU_BARS_VIEW = {json.dumps(BARS_VIEW)};",
        f"export const BAIDU_FACTOR_TABLE = {json.dumps(FACTOR_TABLE)};",
        f"export const BAIDU_ADJUST = {json.dumps(ADJUST)};",
        "export interface BaiduBar {",
        "  symbol: string;",
        "  tradeDate: string;",
        "  open: number;",
        "  high: number;",
        "  low: number;",
        "  close: number;",
        "  volume: number;",
        "  adjustType: string;",
        "  ret1d: number | null;",
        "  ret5d: number | null;",
        "  ret20d: number | null;",
        "  ret60d: number | null;",
        "  atr14: number | null;",
        "  atrPct: number | null;",
        "  atrPctRank60: number | null;",
        "  atrPctRank252: number | null;",
        "  distSma20Pct: number | null;",
        "  distSma50Pct: number | null;",
        "  distSma200Pct: number | null;",
        "  distEma9Pct: number | null;",
        "  distEma21Pct: number | null;",
        "  volRatio20: number | null;",
        "  trendTag: string | null;",
        "  volTag: string | null;",
        "  dsSource: string | null;",
        "}",
        "export const BAIDU_BARS: BaiduBar[] = [",
    ]
    for row in rows:
        (
            symbol, trade_date, open_, high, low, close, volume, adjust,
            ret1, ret5, ret20, ret60,
            atr, atr_pct, rank60, rank252,
            sma20, sma50, sma200, ema9, ema21,
            vol_ratio, trend, vol_tag, source,
        ) = row
        lines.append(
            "  {"
            f" symbol: {json.dumps(symbol)}, tradeDate: {json.dumps(trade_date)},"
            f" open: {num(open_, 4)}, high: {num(high, 4)}, low: {num(low, 4)}, close: {num(close, 4)},"
            f" volume: {int(volume)}, adjustType: {json.dumps(adjust)},"
            f" ret1d: {num(ret1, 6)}, ret5d: {num(ret5, 6)}, ret20d: {num(ret20, 6)}, ret60d: {num(ret60, 6)},"
            f" atr14: {num(atr, 4)}, atrPct: {num(atr_pct, 6)},"
            f" atrPctRank60: {num(rank60, 2)}, atrPctRank252: {num(rank252, 2)},"
            f" distSma20Pct: {num(sma20, 6)}, distSma50Pct: {num(sma50, 6)}, distSma200Pct: {num(sma200, 6)},"
            f" distEma9Pct: {num(ema9, 6)}, distEma21Pct: {num(ema21, 6)},"
            f" volRatio20: {num(vol_ratio, 4)},"
            f" trendTag: {json.dumps(trend)}, volTag: {json.dumps(vol_tag)}, dsSource: {json.dumps(source)} }},"
        )
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(rows)} rows to {OUT} from {path}")


if __name__ == "__main__":
    main()
